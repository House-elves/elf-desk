-- The desk's schema, in H2 (a file under the data directory). One baseline, made when the desk moved from
-- Postgres: varchar without a length is H2's unbounded text, varbinary its unbounded bytes.

-- Which owners and repos the board watches (include), or leaves out (exclude).
create table watch_scope (
    id    bigint generated by default as identity primary key,
    kind  varchar(8)   not null check (kind in ('owner', 'repo')),
    name  varchar(200) not null,
    mode  varchar(8)   not null check (mode in ('include', 'exclude')),
    added timestamp with time zone not null default current_timestamp,
    unique (kind, name)
);

create table setting (
    setting_key   varchar(100) primary key,
    setting_value varchar      not null
);

-- One thread per issue/PR: a single resumable Claude session on the runner. seen: when the thread page last
-- showed it, so an agent answer after that is new ("Answer ready" on the board).
create table thread (
    id             bigint generated by default as identity primary key,
    item_key       varchar(300) not null unique,   -- owner/repo#number
    item_kind      varchar(8)   not null check (item_kind in ('PR', 'ISSUE')),
    title          varchar      not null,
    url            varchar      not null,
    claude_session varchar(64),
    created        timestamp with time zone not null default current_timestamp,
    updated        timestamp with time zone not null default current_timestamp,
    seen           timestamp with time zone
);

-- One agent run. queued = not yet accepted by the runner. fixes: how many fixes a self-review found.
create table job (
    id        bigint generated by default as identity primary key,
    thread_id bigint      not null references thread (id) on delete cascade,
    action    varchar(20) not null,
    prompt    varchar     not null,
    checkout  varchar     not null,  -- JSON for the runner: {repo, number, kind, base}
    untrusted varchar,               -- outsiders' text for the runner's safety triage (first job only)
    state     varchar(10) not null check (state in ('queued', 'running', 'done', 'failed', 'cancelled')),
    error     varchar,
    cost_usd  numeric(10, 4),
    created   timestamp with time zone not null default current_timestamp,
    started   timestamp with time zone,
    finished  timestamp with time zone,
    fixes     integer
);
create index job_thread on job (thread_id, id);
create index job_state on job (state);

-- The conversation as shown in the thread view. job_id: the job that wrote an agent's answer, to find its files.
create table turn (
    id        bigint generated by default as identity primary key,
    thread_id bigint      not null references thread (id) on delete cascade,
    role      varchar(8)  not null check (role in ('you', 'agent', 'system')),
    action    varchar(20),
    text      varchar     not null,
    created   timestamp with time zone not null default current_timestamp,
    job_id    bigint
);
create index turn_thread on turn (thread_id, id);

-- Something postable the agent produced. payload is JSON (see Draft.java).
create table draft (
    id         bigint generated by default as identity primary key,
    thread_id  bigint      not null references thread (id) on delete cascade,
    job_id     bigint      references job (id) on delete set null,
    kind       varchar(10) not null check (kind in ('review', 'comment', 'push', 'issue', 'pr')),
    payload    varchar     not null,
    state      varchar(10) not null check (state in ('draft', 'posted', 'discarded')),
    posted_url varchar,
    posted_at  timestamp with time zone,
    created    timestamp with time zone not null default current_timestamp
);

-- Append-only audit of every write to GitHub, all made by a click.
create table github_action (
    id         bigint generated by default as identity primary key,
    thread_id  bigint       references thread (id) on delete set null,
    draft_id   bigint       references draft (id) on delete set null,
    kind       varchar(20)  not null,
    request    varchar      not null,
    result_url varchar,
    login      varchar(100) not null,
    at         timestamp with time zone not null default current_timestamp
);

-- "Merge on green": PRs the desk merges (through the runner) once CI passes. head_sha is the head you saw when
-- you clicked; the merge is pinned to it. require_approval false: "Merge anyway", without an approval.
create table merge_watch (
    id               bigint generated by default as identity primary key,
    item_key         varchar(300) not null,
    method           varchar(10)  not null check (method in ('merge', 'squash', 'rebase')),
    head_sha         varchar(40)  not null,
    state            varchar(10)  not null check (state in ('waiting', 'merged', 'failed', 'cancelled')),
    outcome          varchar,
    login            varchar(100) not null,
    created          timestamp with time zone not null default current_timestamp,
    checked          timestamp with time zone,
    finished         timestamp with time zone,
    require_approval boolean      not null default true,
    -- At most one waiting watch per PR: the unique index below only sees waiting ones (it's null for the rest).
    waiting_item     varchar(300) generated always as (case when state = 'waiting' then item_key end)
);
create unique index merge_watch_waiting on merge_watch (waiting_item);

-- Items you're involved in but someone else is handling: shown in a collapsed "Ignored" section. An item comes
-- back when someone requests your review or mentions you after you ignored it.
create table ignored_item (
    item_key        varchar(300) primary key,
    login           varchar(100) not null,
    ignored         timestamp with time zone not null default current_timestamp,
    returned_at     timestamp with time zone,
    returned_reason varchar(200)
);

-- Emails you marked Done on the Email tab: their Gmail thread was marked read, and the triage lists them as done.
create table email_done (
    account    varchar not null,
    message_id varchar not null,
    done       timestamp with time zone not null default current_timestamp,
    marked     integer not null default 0,
    primary key (account, message_id)
);

-- Zulip topics you marked Done on the Zulip tab: their messages were marked read. A topic with newer messages
-- than "done" shows again.
create table zulip_done (
    server  varchar not null,
    stream  varchar not null,
    topic   varchar not null,
    done    timestamp with time zone not null default current_timestamp,
    marked  integer not null default 0,
    primary key (server, stream, topic)
);

-- Weekly status drafts you sent to the team yourself (from your own mail client): "I sent it myself" on the
-- Status tab. The draft counts as sent to the team; nothing was emailed by the elf.
create table status_sent_yourself (
    draft   varchar primary key,
    at      timestamp with time zone not null default current_timestamp
);

-- Files the agent left for you in its $ELF_FILES (screenshots, logs): sent by the runner when the job ends,
-- shown with the agent's answer.
create table job_file (
    id           bigint generated by default as identity primary key,
    job_id       bigint    not null references job (id) on delete cascade,
    name         varchar   not null,
    content_type varchar   not null,
    size         integer   not null,
    data         varbinary not null,
    created      timestamp with time zone not null default current_timestamp,
    unique (job_id, name)
);
